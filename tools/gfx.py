def conveyor_cell():
    g = [[0] * 16 for _ in range(16)]
    for y in range(0, 6):
        for x in range(16):
            g[y][x] = ((x + y) // 2) % 3 + 1 if 0 < y < 5 else 3 if y == 0 else 1
    # rouleaux a rayons
    for cx in (4, 12):
        for y in range(7, 15):
            for x in range(cx - 4, cx + 4):
                dx, dy = x - cx + 0.5, y - 10.5
                d = dx * dx + dy * dy
                if d < 14:
                    q = (1 if dx >= 0 else 0) + (2 if dy >= 0 else 0)
                    g[y][x] = (1, 2, 3, 1)[q]
                elif d < 18:
                    g[y][x] = 1
    return g


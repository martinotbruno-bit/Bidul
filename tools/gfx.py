def font_tile(ch):
    rows = FONT[ch].split()
    t = [[0] * 8 for _ in range(8)]
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c == "#":
                t[y][x + 1] = 3
    # ombre portee en couleur 1
    for y in range(7, -1, -1):
        for x in range(7, -1, -1):
            if t[y][x] == 3:
                for dx, dy in ((1, 1), (1, 0), (0, 1)):
                    if x + dx < 8 and y + dy < 8 and t[y + dy][x + dx] == 0:
                        t[y + dy][x + dx] = 1
    return t


def decode(tb):
    t = [[0] * 8 for _ in range(8)]
    for y in range(8):
        for x in range(8):
            t[y][x] = ((tb[y] >> (7 - x)) & 1) | (((tb[y + 8] >> (7 - x)) & 1) << 1)
    return t

def preview(bgdata, spdata, mt_rows, bid):
    try:
        from PIL import Image
    except ImportError:
        return
    P = nes_palette()
    # planche metatuiles
    S = 4
    img = Image.new("RGB", (len(mt_rows) * 18 * S, 18 * S), (40, 40, 40))
    for i, (name, ch, coll, pal, tiles) in enumerate(mt_rows):
        for k, t in enumerate(tiles):
            d = decode(bgdata[t])
            for y in range(8):
                for x in range(8):
                    c = P[BG_PAL[pal][d[y][x]]]
                    ox = i * 18 + (k % 2) * 8 + x
                    oy = (k // 2) * 8 + y
                    for a in range(S):
                        for b in range(S):
                            img.putpixel((ox * S + a, oy * S + b), c)
    img.save(os.path.join(ROOT, "build", "preview_metatiles.png"))
    # planche Bidule
    img = Image.new("RGB", (len(bid) * 18 * S, 26 * S), P[0x01])
    for i, (name, tiles) in enumerate(bid):
        for k, t in enumerate(tiles):
            d = decode(spdata[t])
            for y in range(8):
                for x in range(8):
                    if d[y][x] == 0:
                        continue
                    c = P[SP_PAL[0][d[y][x]]]
                    ox = i * 18 + (k % 2) * 8 + x
                    oy = (k // 2) * 8 + y
                    for a in range(S):
                        for b in range(S):
                            img.putpixel((ox * S + a, oy * S + b), c)
    img.save(os.path.join(ROOT, "build", "preview_bidule.png"))
    # table complete des sprites et decors (palette 0)
    img = Image.new("RGB", (16 * 8 * 2 * 2 + 8, 16 * 8 * 2), (0, 0, 0))
    for bank, data, pal in ((0, bgdata, BG_PAL[1]), (1, spdata, SP_PAL[3])):
        for n in range(256):
            d = decode(data[n])
            for y in range(8):
                for x in range(8):
                    c = P[pal[d[y][x]]]
                    ox = bank * (16 * 8 + 4) + (n % 16) * 8 + x
                    oy = (n // 16) * 8 + y
                    for a in range(2):
                        for b in range(2):
                            img.putpixel((ox * 2 + a, oy * 2 + b), c)
    img.save(os.path.join(ROOT, "build", "preview_chr.png"))



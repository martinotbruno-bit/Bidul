def px(ch):
    return {".": 0, "0": 0, "1": 1, "2": 2, "3": 3}[ch]

def grid(rows, w, h):
    g = [[0] * w for _ in range(h)]
    for y, r in enumerate(rows[:h]):
        for x, c in enumerate(r[:w]):
            g[y][x] = px(c)
    return g

def tile_bytes(t):
    """t : 8x8 liste de couleurs -> 16 octets au format NES (2 plans)."""
    lo, hi = [], []
    for y in range(8):
        a = b = 0
        for x in range(8):
            v = t[y][x]
            a |= (v & 1) << (7 - x)
            b |= ((v >> 1) & 1) << (7 - x)
        lo.append(a); hi.append(b)
    return bytes(lo + hi)

def cut(g, tx, ty):
    return [row[tx * 8:tx * 8 + 8] for row in g[ty * 8:ty * 8 + 8]]

def hflip(g):
    return [list(reversed(r)) for r in g]

class Bank:
    def __init__(self, name, reserved=()):
        self.name = name
        self.tiles = {}            # bytes -> index
        self.data = [bytes(16)] * 256
        self.free = [i for i in range(256) if i not in reserved]
        self.add(tuple(tuple(r) for r in [[0]*8]*8))  # tuile 0 = vide

    def add(self, t, index=None):
        key = tile_bytes(t)
        if index is None and key in self.tiles:
            return self.tiles[key]
        if index is None:
            index = self.free.pop(0)
        elif index in self.free:
            self.free.remove(index)
        self.data[index] = key
        self.tiles.setdefault(key, index)
        return index

    def add_block(self, g, tw, th):
        return [self.add(cut(g, x, y)) for y in range(th) for x in range(tw)]


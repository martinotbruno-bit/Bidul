def empty_cell():
    g = [[0] * 16 for _ in range(16)]
    for y in range(0, 16, 2):
        g[y][0] = 1
    return g

def brick_cell():
    g = [[2] * 16 for _ in range(16)]
    for y in range(16):
        for x in range(16):
            if y in (0, 8):
                g[y][x] = 1
            elif y < 8 and x == 7:
                g[y][x] = 1
            elif y > 8 and x == 15:
                g[y][x] = 1
            elif y in (1, 9):
                g[y][x] = 3
    return g

def girder_cell():
    g = [[0] * 16 for _ in range(16)]
    for x in range(16):
        g[0][x] = 3; g[1][x] = 2; g[2][x] = 1
        g[13][x] = 3; g[14][x] = 2; g[15][x] = 1
    for y in range(3, 13):
        d = y - 3
        for x in range(16):
            if x % 16 in (d % 10, (9 - d) % 10 + 6) or x in (0, 15):
                g[y][x] = 2
    return g

def block_cell():
    g = [[2] * 16 for _ in range(16)]
    for i in range(16):
        g[0][i] = g[15][i] = g[i][0] = g[i][15] = 1
    for i in range(1, 15):
        g[1][i] = 3; g[i][1] = 3
    for (x, y) in ((3, 3), (12, 3), (3, 12), (12, 12)):
        g[y][x] = 1; g[y][x + 1] = 3
    return g

